import { test, mock } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, readdirSync, existsSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { sync } from '../src/sync.js';
import { MARKER } from '../src/paths.js';

// A fake repo: vendor/up/skills/<name>/SKILL.md (+ references), a manifest, and a factory Skill.
function fakeRepo(manifest, skills, flow = 'Invoke `renamed`.\n') {
  const root = mkdtempSync(join(tmpdir(), 'tds-sync-'));
  const skillsDir = join(root, 'skills');
  mkdirSync(join(skillsDir, 'factory'), { recursive: true });
  writeFileSync(join(skillsDir, 'factory', 'SKILL.md'), flow);
  for (const [name, files] of Object.entries(skills)) {
    for (const [file, text] of Object.entries(files)) {
      mkdirSync(join(root, 'vendor/up/skills', name, file, '..'), { recursive: true });
      writeFileSync(join(root, 'vendor/up/skills', name, file), text);
    }
  }
  writeFileSync(join(root, 'skills.manifest.json'), JSON.stringify({ skills: manifest }));
  return { root, skillsDir };
}

const quietSync = (opts) => {
  const log = mock.method(console, 'log', () => {});
  try {
    sync(opts);
  } finally {
    log.mock.restore();
  }
};

const alpha = {
  'SKILL.md': '---\nname: alpha\ndisable-model-invocation: true\n---\nRun /alpha or /alpha <path>, not /alpha-extra.\n',
  'references/notes.md': 'Generated by: /alpha skill\n',
};

test('sync ships a renamed skill with the name set and old mentions rewritten in every Markdown file', () => {
  const { root, skillsDir } = fakeRepo([{ path: 'vendor/up/skills/alpha', as: 'renamed' }], { alpha });
  quietSync({ root, skillsDir });
  const skill = readFileSync(join(skillsDir, 'renamed', 'SKILL.md'), 'utf8');
  assert.match(skill, /^name: renamed$/m);
  assert.match(skill, /Run \/renamed or \/renamed <path>, not \/alpha-extra\./);
  assert.equal(readFileSync(join(skillsDir, 'renamed', 'references', 'notes.md'), 'utf8'), 'Generated by: /renamed skill\n');
  assert.ok(!existsSync(join(skillsDir, 'alpha')));
});

test('sync removes the model-invocation flag only from skills the factory invokes', () => {
  const beta = { 'SKILL.md': '---\nname: beta\ndisable-model-invocation: true\n---\n' };
  const { root, skillsDir } = fakeRepo(
    [{ path: 'vendor/up/skills/alpha', as: 'renamed' }, 'vendor/up/skills/beta'],
    { alpha, beta },
  );
  quietSync({ root, skillsDir });
  assert.doesNotMatch(readFileSync(join(skillsDir, 'renamed', 'SKILL.md'), 'utf8'), /disable-model-invocation/);
  assert.match(readFileSync(join(skillsDir, 'beta', 'SKILL.md'), 'utf8'), /disable-model-invocation/);
});

test('sync marks what it ships and refuses to overwrite a folder it did not sync', () => {
  const { root, skillsDir } = fakeRepo(['vendor/up/skills/alpha'], { alpha }, '');
  mkdirSync(join(skillsDir, 'alpha'));
  assert.throws(() => quietSync({ root, skillsDir }), /refusing to overwrite/);
  writeFileSync(join(skillsDir, 'alpha', MARKER), '');
  quietSync({ root, skillsDir });
  assert.ok(existsSync(join(skillsDir, 'alpha', 'references', 'notes.md')));
});

const beta = { 'SKILL.md': '---\nname: beta\n---\n' };

test('sync refuses a shipped name that is not lowercase letters, digits and hyphens, naming the entry', () => {
  for (const as of ['../x', 'Upper', 'a b', '..', 'a/b']) {
    const { root, skillsDir } = fakeRepo([{ path: 'vendor/up/skills/alpha', as }], { alpha });
    assert.throws(() => quietSync({ root, skillsDir }), (err) => err.message.includes(JSON.stringify(as)), as);
    assert.deepEqual(readdirSync(skillsDir), ['factory'], as);
  }
});

test('sync refuses a source path that leaves the repository, naming the entry', () => {
  const { root, skillsDir } = fakeRepo(['../outside/skills/alpha'], { alpha });
  mkdirSync(join(root, '..', 'outside', 'skills', 'alpha'), { recursive: true });
  writeFileSync(join(root, '..', 'outside', 'skills', 'alpha', 'SKILL.md'), '---\nname: alpha\n---\n');
  assert.throws(() => quietSync({ root, skillsDir }), /"\.\.\/outside\/skills\/alpha".*leaves the repository/);
  assert.deepEqual(readdirSync(skillsDir), ['factory']);
});

test('sync validates every entry before it writes any', () => {
  const { root, skillsDir } = fakeRepo(
    ['vendor/up/skills/beta', { path: 'vendor/up/skills/alpha', as: 'Bad Name' }],
    { alpha, beta },
  );
  assert.throws(() => quietSync({ root, skillsDir }), /Bad Name/);
  assert.deepEqual(readdirSync(skillsDir), ['factory']);
});

test('sync refuses a symlink inside a shipped skill, naming the skill and the link, and writes nothing for it', () => {
  const { root, skillsDir } = fakeRepo(['vendor/up/skills/alpha'], { alpha }, '');
  symlinkSync('/etc/hostname', join(root, 'vendor/up/skills/alpha', 'link.md'));
  assert.throws(() => quietSync({ root, skillsDir }), /alpha.*link\.md|link\.md.*alpha/);
  assert.ok(!existsSync(join(skillsDir, 'alpha')));
});

test('sync rewrites only the literal old name, so a regex character in it is not a wildcard', () => {
  const dot = { 'SKILL.md': '---\nname: a.b\n---\nRun /a.b, not /axb.\n' };
  const { root, skillsDir } = fakeRepo([{ path: 'vendor/up/skills/a.b', as: 'renamed' }], { 'a.b': dot });
  quietSync({ root, skillsDir });
  assert.match(readFileSync(join(skillsDir, 'renamed', 'SKILL.md'), 'utf8'), /Run \/renamed, not \/axb\./);
});

test('sync names a malformed manifest entry instead of throwing a bare TypeError', () => {
  for (const entry of [{ as: 'x' }, { path: 5 }, { path: 'vendor/up/skills/alpha', as: 5 }, 42, null]) {
    const { root, skillsDir } = fakeRepo([entry], { alpha });
    assert.throws(() => quietSync({ root, skillsDir }), (err) => !(err instanceof TypeError) && err.message.includes(JSON.stringify(entry)), JSON.stringify(entry));
  }
});

test('sync accepts an in-repo source whose folder name merely starts with two dots', () => {
  const { root, skillsDir } = fakeRepo(['..cache/skills/alpha'], {}, '');
  mkdirSync(join(root, '..cache', 'skills', 'alpha'), { recursive: true });
  writeFileSync(join(root, '..cache', 'skills', 'alpha', 'SKILL.md'), '---\nname: alpha\n---\n');
  quietSync({ root, skillsDir });
  assert.ok(existsSync(join(skillsDir, 'alpha', 'SKILL.md')));
});

test('sync refuses a source that is, or sits under, a symlink', () => {
  for (const link of ['vendor/up/skills/alpha', 'vendor/up']) {
    const { root, skillsDir } = fakeRepo(['vendor/up/skills/alpha'], {}, '');
    mkdirSync(join(root, 'real', 'skills', 'alpha'), { recursive: true });
    writeFileSync(join(root, 'real', 'skills', 'alpha', 'SKILL.md'), '---\nname: alpha\n---\n');
    const target = link === 'vendor/up' ? join(root, 'real') : join(root, 'real', 'skills', 'alpha');
    mkdirSync(join(root, link, '..'), { recursive: true });
    symlinkSync(target, join(root, link));
    assert.throws(() => quietSync({ root, skillsDir }), /symlink/, link);
    assert.deepEqual(readdirSync(skillsDir), ['factory'], link);
  }
});

test('sync refuses two entries that ship under the same name', () => {
  const { root, skillsDir } = fakeRepo(['vendor/up/skills/alpha', { path: 'vendor/up/skills/beta', as: 'alpha' }], { alpha, beta });
  assert.throws(() => quietSync({ root, skillsDir }), /alpha/);
  assert.deepEqual(readdirSync(skillsDir), ['factory']);
});

test('sync replaces the files of a folder it synced before, dropping stale ones', () => {
  const { root, skillsDir } = fakeRepo(['vendor/up/skills/alpha'], { alpha }, '');
  mkdirSync(join(skillsDir, 'alpha'));
  writeFileSync(join(skillsDir, 'alpha', MARKER), '');
  writeFileSync(join(skillsDir, 'alpha', 'stale.md'), 'old');
  quietSync({ root, skillsDir });
  assert.ok(!existsSync(join(skillsDir, 'alpha', 'stale.md')));
  assert.ok(existsSync(join(skillsDir, 'alpha', 'SKILL.md')));
});

test('sync ships a skill that holds a directory named like a Markdown file', () => {
  const { root, skillsDir } = fakeRepo(['vendor/up/skills/alpha'], { alpha }, '');
  mkdirSync(join(root, 'vendor/up/skills/alpha', 'weird.md'));
  writeFileSync(join(root, 'vendor/up/skills/alpha', 'weird.md', 'inner.txt'), 'x');
  quietSync({ root, skillsDir });
  assert.ok(existsSync(join(skillsDir, 'alpha', 'weird.md', 'inner.txt')));
});

test('sync refuses a source that is the repository root or sits inside the skills folder', () => {
  for (const entry of [{ path: '.', as: 'zzz' }, 'skills/factory']) {
    const { root, skillsDir } = fakeRepo([entry], {}, '---\nname: factory\n---\n');
    writeFileSync(join(root, 'SKILL.md'), '---\nname: root\n---\n');
    writeFileSync(join(skillsDir, 'factory', MARKER), '');
    assert.throws(() => quietSync({ root, skillsDir }), /repository root|skills folder/, JSON.stringify(entry));
    assert.ok(existsSync(join(skillsDir, 'factory', 'SKILL.md')), JSON.stringify(entry));
  }
});

test('sync removes a marked folder that left the manifest and keeps skills it did not sync', () => {
  const { root, skillsDir } = fakeRepo(['vendor/up/skills/alpha'], { alpha });
  mkdirSync(join(skillsDir, 'obsolete'));
  writeFileSync(join(skillsDir, 'obsolete', 'SKILL.md'), 'old');
  writeFileSync(join(skillsDir, 'obsolete', MARKER), 'vendor/up/skills/obsolete\n');
  mkdirSync(join(skillsDir, 'mine'));
  writeFileSync(join(skillsDir, 'mine', 'SKILL.md'), 'ours');
  quietSync({ root, skillsDir });
  assert.ok(!existsSync(join(skillsDir, 'obsolete')));
  assert.ok(existsSync(join(skillsDir, 'mine', 'SKILL.md')));
  assert.ok(existsSync(join(skillsDir, 'factory', 'SKILL.md')));
  assert.ok(existsSync(join(skillsDir, 'alpha', 'SKILL.md')));
});

test('a manifest that fails validation removes nothing', () => {
  const { root, skillsDir } = fakeRepo(['vendor/up/skills/missing'], {});
  mkdirSync(join(skillsDir, 'obsolete'));
  writeFileSync(join(skillsDir, 'obsolete', MARKER), 'x\n');
  assert.throws(() => quietSync({ root, skillsDir }));
  assert.ok(existsSync(join(skillsDir, 'obsolete')));
});
