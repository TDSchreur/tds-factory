import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { repo } from './git-repo.js';

const cli = resolve('bin/tds-factory.js');
const rules = (cwd, ...args) => spawnSync(process.execPath, [cli, 'rules', ...args], { cwd, encoding: 'utf8' });

function project() {
  const cwd = repo();
  mkdirSync(join(cwd, '.github', 'instructions'), { recursive: true });
  writeFileSync(join(cwd, '.github', 'instructions', 'dashboard.instructions.md'), '---\ndescription: Dashboard\napplyTo: "dashboard/**, src/dashboard.js"\n---\n\n# Dashboard rules\n');
  writeFileSync(join(cwd, '.github', 'instructions', 'general.instructions.md'), '# General rules\n');
  return cwd;
}
const read = (cwd, name) => readFileSync(join(cwd, '.claude', 'rules', name), 'utf8');

test('rules turns applyTo into paths and keeps the body', () => {
  const cwd = project();
  const result = rules(cwd);
  assert.equal(result.status, 0, result.stderr);
  const dashboard = read(cwd, 'dashboard.md');
  assert.match(dashboard, /^---\npaths:\n {2}- "dashboard\/\*\*"\n {2}- "src\/dashboard\.js"\n---\n<!-- generated by tds-factory rules from \.github\/instructions\/dashboard\.instructions\.md; sha256:[0-9a-f]{64} -->\n# Dashboard rules\n$/);
  assert.doesNotMatch(dashboard, /description/);
});

test('an unscoped instruction file becomes a rule without frontmatter', () => {
  const cwd = project();
  rules(cwd);
  assert.match(read(cwd, 'general.md'), /^<!-- generated by tds-factory rules from [^\n]+ -->\n# General rules\n$/);
});

test('running rules again replaces an unedited copy and follows the source', () => {
  const cwd = project();
  rules(cwd);
  writeFileSync(join(cwd, '.github', 'instructions', 'general.instructions.md'), '# General rules v2\n');
  const again = rules(cwd);
  assert.equal(again.status, 0, again.stderr);
  assert.match(read(cwd, 'general.md'), /v2/);
});

test('an edited copy and a rule the user wrote are kept unless --force', () => {
  const cwd = project();
  rules(cwd);
  writeFileSync(join(cwd, '.claude', 'rules', 'general.md'), `${read(cwd, 'general.md')}my note\n`);
  writeFileSync(join(cwd, '.claude', 'rules', 'dashboard.md'), 'mine\n');
  const kept = rules(cwd);
  assert.match(kept.stdout, /kept \.claude\/rules\/general\.md/);
  assert.match(kept.stdout, /kept \.claude\/rules\/dashboard\.md/);
  assert.match(read(cwd, 'general.md'), /my note/);
  assert.equal(read(cwd, 'dashboard.md'), 'mine\n');
  assert.equal(rules(cwd, '--force').status, 0);
  assert.doesNotMatch(read(cwd, 'general.md'), /my note/);
  assert.match(read(cwd, 'dashboard.md'), /paths:/);
});

test('--dry-run writes nothing, and a bad applyTo or a missing source folder is refused', () => {
  const cwd = project();
  const dry = rules(cwd, '--dry-run');
  assert.match(dry.stdout, /would write \.claude\/rules\/dashboard\.md/);
  assert.ok(!existsSync(join(cwd, '.claude')));
  writeFileSync(join(cwd, '.github', 'instructions', 'bad.instructions.md'), '---\napplyTo: "x\n---\n');
  const bad = rules(cwd);
  assert.notEqual(bad.status, 0);
  assert.match(bad.stderr, /bad\.instructions\.md:2: .*unclosed quote/);
  assert.notEqual(rules(repo()).status, 0);
});

test('rules never writes through a symbolic link, not even with --force', () => {
  const outside = repo();
  const cwd = project();
  mkdirSync(join(cwd, '.claude', 'rules'), { recursive: true });
  symlinkSync(join(outside, 'planted.md'), join(cwd, '.claude', 'rules', 'general.md'));
  for (const args of [[], ['--force']]) {
    const result = rules(cwd, ...args);
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /symbolic link/);
  }
  assert.ok(!existsSync(join(outside, 'planted.md')));
  const folder = project();
  mkdirSync(join(folder, '.claude'));
  symlinkSync(outside, join(folder, '.claude', 'rules'));
  assert.match(rules(folder).stderr, /symbolic link/);
  assert.ok(!existsSync(join(outside, 'general.md')));
});
