import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { parseGuide, insideProject } from './guides.js';

// Claude Code reads .claude/rules/*.md and loads a rule with `paths:` only when it works on a matching file. The Copilot instruction files
// in .github/instructions/ are the source (ADR 0022); the copies carry a marker with a hash so an edited copy is kept, as install keeps an edited agent file.
const SOURCE_DIR = '.github/instructions';
const TARGET_DIR = '.claude/rules';
const MARKER = /^<!-- generated by tds-factory rules from (\S+); sha256:([0-9a-f]{64}) -->\r?\n/m;
const MAX_FILE = 1 << 20;
const sha = (text) => createHash('sha256').update(text).digest('hex');
const clean = (text) => String(text).replace(/[\x00-\x1f\x7f-\x9f]/g, '?');

const body = (text) => {
  const lines = text.replace(/^\uFEFF/, '').split(/\r?\n/);
  if (lines[0]?.trim() !== '---') return text;
  const end = lines.findIndex((l, i) => i > 0 && l.trim() === '---');
  return end < 0 ? text : lines.slice(end + 1).join('\n');
};

// The rule file for one instruction file: `paths:` for a scoped guide, no frontmatter for an unscoped one (Claude Code then always loads it).
export function ruleFor(text, source) {
  const { globs, problem } = parseGuide(text);
  if (problem) throw new Error(`${source}:${problem.line}: ${problem.message}`);
  const front = globs.length ? `---\npaths:\n${globs.map((g) => `  - ${JSON.stringify(g)}`).join('\n')}\n---\n` : '';
  const rest = body(text).replace(/^\n+/, '');
  return `${front}<!-- generated by tds-factory rules from ${source}; sha256:${sha(front + rest)} -->\n${rest}`;
}

// An existing copy is ours and unedited when it has the marker and the rest hashes to the recorded value.
function untouched(existing) {
  const m = existing.match(MARKER);
  return !!m && sha(existing.replace(MARKER, '')) === m[2];
}

// The project is not trusted: a link at the destination, or in a folder on the way to it, must not lead a write outside the project.
const isLink = (file) => fs.lstatSync(file, { throwIfNoEntry: false })?.isSymbolicLink() ?? false;
function checkFolder(project, dir) {
  let at = dir;
  while (at !== project) {
    if (isLink(at)) throw new Error(`${path.relative(project, at).replace(/\\/g, '/')} is a symbolic link; remove it first`);
    at = path.dirname(at);
  }
  if (fs.existsSync(dir) && !insideProject(project, dir)) throw new Error(`${clean(path.relative(project, dir))} resolves to a place outside the project`);
}

export function syncRules({ project = process.cwd(), force = false, dryRun = false, log = console.log } = {}) {
  const source = path.join(project, SOURCE_DIR);
  if (!fs.existsSync(source)) throw new Error(`there is no ${SOURCE_DIR} folder to copy from`);
  checkFolder(project, source);
  const targetDir = path.join(project, TARGET_DIR);
  checkFolder(project, targetDir);
  const names = fs.readdirSync(source, { withFileTypes: true }).filter((e) => e.isFile() && e.name.endsWith('.instructions.md')).map((e) => e.name).sort();
  const result = { written: [], kept: [] };
  for (const name of names) {
    const from = path.join(source, name);
    if (fs.statSync(from).size > MAX_FILE) throw new Error(`${clean(name)} is larger than 1 MiB`);
    const file = ruleFor(fs.readFileSync(from, 'utf8'), `${SOURCE_DIR}/${name}`);
    const dest = path.join(targetDir, name.replace(/\.instructions\.md$/, '.md'));
    const destRel = `${TARGET_DIR}/${path.basename(dest)}`;
    // A link at the destination is never followed, not even with --force.
    if (isLink(dest)) throw new Error(`${clean(destRel)} is a symbolic link; remove it first`);
    const existing = fs.existsSync(dest) && fs.statSync(dest).isFile() ? fs.readFileSync(dest, 'utf8') : undefined;
    if (existing !== undefined && !force && !untouched(existing)) {
      result.kept.push(destRel);
      log(`kept ${clean(destRel)} (not generated by tds-factory rules, or edited; --force replaces it)`);
      continue;
    }
    if (!dryRun) {
      fs.mkdirSync(targetDir, { recursive: true });
      // Write beside the target and rename, so a file appearing at the target in between is replaced, not written through.
      const temp = `${dest}.${process.pid}.tmp`;
      fs.writeFileSync(temp, file, { flag: 'wx' });
      fs.renameSync(temp, dest);
    }
    result.written.push(destRel);
    log(`${dryRun ? 'would write' : 'wrote'} ${clean(destRel)}`);
  }
  return result;
}
