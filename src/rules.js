import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { parseGuide } from './guides.js';

// Claude Code reads .claude/rules/*.md and loads a rule with `paths:` only when it works on a matching file. The Copilot instruction files
// in .github/instructions/ are the source (ADR 0022); the copies carry a marker with a hash so an edited copy is kept, as install keeps an edited agent file.
const SOURCE_DIR = path.join('.github', 'instructions');
const TARGET_DIR = path.join('.claude', 'rules');
const MARKER = /^<!-- generated by tds-factory rules from (\S+); sha256:([0-9a-f]{64}) -->\r?\n/m;
const MAX_FILE = 1 << 20;
const sha = (text) => createHash('sha256').update(text).digest('hex');

const body = (text) => {
  const lines = text.replace(/^\uFEFF/, '').split(/\r?\n/);
  if (lines[0]?.trim() !== '---') return text;
  const end = lines.findIndex((l, i) => i > 0 && l.trim() === '---');
  return end < 0 ? text : lines.slice(end + 1).join('\n');
};

// The rule file for one instruction file: `paths:` for a scoped guide, no frontmatter for an unscoped one (Claude Code then always loads it).
export function ruleFor(text, source) {
  const { globs, problem } = parseGuide(text);
  if (problem) throw new Error(`${source}:${problem.line}: ${problem.message}`);
  const front = globs.length ? `---\npaths:\n${globs.map((g) => `  - ${JSON.stringify(g)}`).join('\n')}\n---\n` : '';
  const content = `${front}${body(text).replace(/^\n+/, '')}`;
  return { content, file: `${front}<!-- generated by tds-factory rules from ${source}; sha256:${sha(content)} -->\n${body(text).replace(/^\n+/, '')}` };
}

// An existing copy is ours and unedited when it has the marker and the rest hashes to the recorded value.
function untouched(existing) {
  const m = existing.match(MARKER);
  return !!m && sha(existing.replace(MARKER, '')) === m[2];
}

export function syncRules({ project = process.cwd(), force = false, dryRun = false, log = console.log } = {}) {
  const source = path.join(project, SOURCE_DIR);
  if (!fs.existsSync(source)) throw new Error(`there is no ${SOURCE_DIR.replace(/\\/g, '/')} folder to copy from`);
  const names = fs.readdirSync(source, { withFileTypes: true }).filter((e) => e.isFile() && e.name.endsWith('.instructions.md')).map((e) => e.name).sort();
  const result = { written: [], kept: [] };
  for (const name of names) {
    const from = path.join(source, name);
    if (fs.statSync(from).size > MAX_FILE) throw new Error(`${name} is larger than 1 MiB`);
    const rel = `${SOURCE_DIR.replace(/\\/g, '/')}/${name}`;
    const { file } = ruleFor(fs.readFileSync(from, 'utf8'), rel);
    const dest = path.join(project, TARGET_DIR, name.replace(/\.instructions\.md$/, '.md'));
    const destRel = path.relative(project, dest).replace(/\\/g, '/');
    const existing = fs.existsSync(dest) && fs.statSync(dest).isFile() ? fs.readFileSync(dest, 'utf8') : undefined;
    if (existing !== undefined && !force && !untouched(existing)) {
      result.kept.push(destRel);
      log(`kept ${destRel} (not generated by tds-factory rules, or edited; --force replaces it)`);
      continue;
    }
    if (!dryRun) { fs.mkdirSync(path.dirname(dest), { recursive: true }); fs.writeFileSync(dest, file); }
    result.written.push(destRel);
    log(`${dryRun ? 'would write' : 'wrote'} ${destRel}`);
  }
  return result;
}
